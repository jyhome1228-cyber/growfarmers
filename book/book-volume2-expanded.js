Object.entries(FARMERS_BOOK_VOLUME2_EXPANSION).forEach(([issue, chapterExtras]) => {
  const story = typeof FARMERS_BOOK !== "undefined" ? FARMERS_BOOK[issue] : null;
  if (!story || !Array.isArray(story.chapters)) return;

  story.chapters.forEach((chapter, chapterIndex) => {
    const extras = chapterExtras[chapterIndex] || [];
    extras.forEach((text) => {
      if (!chapter.paragraphs.includes(text)) chapter.paragraphs.push(text);
    });
  });
});

const expandedVolume2Issue = window.location.hash.match(/^#issue-(\d{2})$/)?.[1];
if (expandedVolume2Issue && FARMERS_BOOK_VOLUME2_EXPANSION[expandedVolume2Issue] && typeof openReader === "function") {
  openReader(expandedVolume2Issue, document.querySelector(`[data-issue="${expandedVolume2Issue}"]`));
}
