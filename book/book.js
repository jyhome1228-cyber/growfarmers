const reader = document.getElementById("bookReader");
const readerImage = document.getElementById("readerImage");
const readerIssue = document.getElementById("readerIssue");
const readerCategory = document.getElementById("readerCategory");
const readerTitle = document.getElementById("readerTitle");
const readerDeck = document.getElementById("readerDeck");
const readerBody = document.getElementById("readerBody");
let lastTrigger = null;

function renderBody(chapters) {
  readerBody.innerHTML = "";
  chapters.forEach((chapter) => {
    const heading = document.createElement("h3");
    heading.textContent = chapter.title;
    readerBody.appendChild(heading);
    chapter.paragraphs.forEach((text) => {
      const paragraph = document.createElement("p");
      paragraph.textContent = text;
      readerBody.appendChild(paragraph);
    });
  });
}

function openReader(issue, trigger) {
  const story = FARMERS_BOOK[issue];
  if (!story || !reader) return;
  lastTrigger = trigger || null;
  readerImage.src = story.image;
  readerImage.alt = story.alt;
  readerIssue.textContent = `ISSUE ${issue}`;
  readerCategory.textContent = story.category;
  readerTitle.textContent = story.title;
  readerDeck.textContent = story.deck;
  renderBody(story.chapters);
  reader.classList.add("is-open");
  reader.setAttribute("aria-hidden", "false");
  document.body.classList.add("reader-open");
  history.replaceState(null, "", `#issue-${issue}`);
  requestAnimationFrame(() => document.querySelector(".book-reader-close")?.focus());
}

function closeReader() {
  if (!reader || !reader.classList.contains("is-open")) return;
  reader.classList.remove("is-open");
  reader.setAttribute("aria-hidden", "true");
  document.body.classList.remove("reader-open");
  history.replaceState(null, "", window.location.pathname + window.location.search);
  if (lastTrigger) lastTrigger.focus();
}

document.querySelectorAll(".book-card").forEach((card) => {
  card.addEventListener("click", () => openReader(card.dataset.issue, card));
});

document.querySelectorAll("[data-close-reader]").forEach((button) => {
  button.addEventListener("click", closeReader);
});

document.addEventListener("keydown", (event) => {
  if (event.key === "Escape") closeReader();
});

const initialIssue = window.location.hash.match(/^#issue-(\d{2})$/)?.[1];
if (initialIssue && FARMERS_BOOK[initialIssue]) {
  openReader(initialIssue, document.querySelector(`[data-issue="${initialIssue}"]`));
}